// Regenerates src/guide-label-names.ts from a Lumiverse checkout's translations, so the guide
// ring can find a control whatever language Lumiverse is shown in.
// Usage: bun scripts/guide-label-names.ts <Lumiverse>/frontend/src/i18n/locales
import { readFileSync, readdirSync, writeFileSync } from 'fs';
import { guideLabelWords } from '../src/guide-text';

const localesDir = process.argv[2];
if (!localesDir) { console.error('Usage: bun scripts/guide-label-names.ts <Lumiverse>/frontend/src/i18n/locales'); process.exit(1); }
const flatten = (value: unknown, prefix = '', out: Record<string, string> = {}) => {
  if (typeof value === 'string') out[prefix] = value;
  else if (value && typeof value === 'object') for (const [key, child] of Object.entries(value)) flatten(child, prefix ? `${prefix}.${key}` : key, out);
  return out;
};
const languages = readdirSync(localesDir);
const strings = Object.fromEntries(languages.map(language => [language, Object.assign({}, ...readdirSync(`${localesDir}/${language}`)
  .filter(file => file.endsWith('.json'))
  .map(file => flatten(JSON.parse(readFileSync(`${localesDir}/${language}/${file}`, 'utf8')), file.replace('.json', ''))))])) as Record<string, Record<string, string>>;

const labels = new Set<string>();
for (const file of ['feature-tutorials.ts', 'preset-sampler-guide.ts']) {
  for (const match of readFileSync(`${import.meta.dir}/../src/${file}`, 'utf8').matchAll(/\*\*([^*]+)\*\*/g)) labels.add(match[1]);
}
const table: Record<string, string[]> = {};
for (const label of [...labels].sort()) {
  const wanted = guideLabelWords(label);
  const keys = Object.entries(strings.en ?? {}).filter(([, value]) => guideLabelWords(value) === wanted).map(([key]) => key);
  const names = new Set<string>();
  for (const language of languages) for (const key of keys) {
    const value = strings[language][key];
    if (value && !value.includes('{{') && guideLabelWords(value) && guideLabelWords(value) !== wanted) names.add(guideLabelWords(value));
  }
  if (names.size) table[label] = [...names].sort();
}
writeFileSync(`${import.meta.dir}/../src/guide-label-names.ts`, `// Generated by scripts/guide-label-names.ts from Lumiverse's translations (${languages.join(', ')}).
// Other names each guide label has in Lumiverse's interface, already normalized.
export const guideLabelNames: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(table, null, 2)};
`);
console.log(`${Object.keys(table).length} of ${labels.size} labels have translated names.`);
